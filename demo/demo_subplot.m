function pos = local_normPosInFigure(obj, fig)
%LOCAL_NORMPOSINFIGURE Get normalized object position in figure coordinates.
%
% annotation uses normalized figure coordinates. For axes inside tiledlayout,
% ax.Position may be layout-managed and not always directly comparable to
% figure coordinates. getpixelposition(..., true) is used first.

drawnow;

oldFigUnits = fig.Units;
fig.Units = "pixels";
figPixelPos = fig.Position;
fig.Units = oldFigUnits;

try
    objPixelPos = getpixelposition(obj, true);
    pos = [ ...
        objPixelPos(1) / figPixelPos(3), ...
        objPixelPos(2) / figPixelPos(4), ...
        objPixelPos(3) / figPixelPos(3), ...
        objPixelPos(4) / figPixelPos(4)];
catch
    % Fallback for objects that do not support getpixelposition.
    oldUnits = obj.Units;
    obj.Units = "normalized";
    pos = obj.Position;
    obj.Units = oldUnits;
end

pos = local_clipNormPos(pos);
end

function pos = local_clipNormPos(pos)
