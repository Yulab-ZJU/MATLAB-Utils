%% demo_subplot
% Demonstration of mu.subplot.
%
% This demo covers:
%   1. H5/CSS-like margins and paddings
%   2. Spanning index in manual-position mode
%   3. Parent as tiledlayout
%   4. PositionType in manual-position mode
%
% Requirements:
%   - Updated mu.subplot supporting:
%       index = [rowStart, colStart, rowSpan, colSpan]
%       indexMode = "linear" | "subscript" | "span" | "auto"
%       Parent = tiledlayout object
%       PositionType = "position" | "outerposition"

ccc;

oldDefaultAxesBox = get(0, "DefaultAxesBox");
cleanupObj = onCleanup(@() set(0, "DefaultAxesBox", oldDefaultAxesBox));

set(0, "DefaultAxesBox", "on");

%% Colors for annotation

C.margin  = [0.85, 0.20, 0.10];
C.padding = [0.10, 0.35, 0.85];
C.grid    = [0.20, 0.20, 0.20];
C.span    = [0.10, 0.60, 0.25];
C.tile    = [0.55, 0.25, 0.75];
C.outer   = [0.95, 0.55, 0.10];

%% Demo 1: H5/CSS-like margins and paddings

fig1 = figure( ...
    "Name", "mu.subplot demo 1: margins and paddings", ...
    "WindowState", "maximized");

margins  = [1/9, 1/18, 2/9, 1/9];   % [left, right, bottom, top], relative to figure
padding1 = [1/5, 1/2, 1/6, 1/6];    % [left, right, bottom, top], relative to div
padding2 = zeros(1, 4);

% div1
[div1Ax, div1Opts] = mu.subplot(fig1, 1, 2, 1, ...
    "margins", margins, ...
    "shape", "fill");
text(div1Ax, 0.05, 0.95, "div1", "Color", "r", "FontWeight", "bold");
local_prepareBoxAxes(div1Ax);

% ax1
[ax1, ax1Opts] = mu.subplot(fig1, 1, 2, 1, ...
    "margins", margins, ...
    "paddings", padding1);
text(ax1, 0.05, 0.95, "ax1", "Color", "r", "FontWeight", "bold");
title(ax1, "paddings create inner space inside div1");

% div2
[div2Ax, div2Opts] = mu.subplot(fig1, 1, 2, 2, ...
    "margins", margins, ...
    "shape", "fill");
text(div2Ax, 0.05, 0.95, "div2", "Color", "r", "FontWeight", "bold");
local_prepareBoxAxes(div2Ax);

% ax2
[ax2, ax2Opts] = mu.subplot(fig1, 1, 2, 2, ...
    "margins", margins, ...
    "paddings", padding2, ...
    "nSize", [1/4, 1/2], ...
    "alignment", "left-bottom");
text(ax2, 0.05, 0.95, "ax2", "Color", "r", "FontWeight", "bold");
title(ax2, "nSize + alignment inside div2");

local_annotateBoxModel(fig1, div1Opts, div2Opts, ax1Opts, C);

%% Demo 2: Spanning index in manual-position mode

fig2 = figure( ...
    "Name", "mu.subplot demo 2: spanning index", ...
    "WindowState", "maximized");

row = 3;
col = 4;

margins2  = [0.06, 0.04, 0.08, 0.07];
paddings2 = [0.08, 0.05, 0.10, 0.08];

% Explicit spanning index: [rowStart, colStart, rowSpan, colSpan]
[axSpan1, optsSpan1] = mu.subplot(fig2, row, col, [1, 1, 2, 2], ...
    "margins", margins2, ...
    "paddings", paddings2, ...
    "indexMode", "span", ...
    "divBox", "show");
plot(axSpan1, rand(20, 1), "LineWidth", 1.4);
title(axSpan1, "index = [1, 1, 2, 2], indexMode = ""span""");

% Backward-compatible subscript index: [row, col]
[axSingle, optsSingle] = mu.subplot(fig2, row, col, [1, 4], ...
    "margins", margins2, ...
    "paddings", paddings2);
bar(axSingle, rand(1, 5));
title(axSingle, "index = [1, 4] as [row, col]");

% Linear vector spanning index. In a 3-by-4 grid, [8, 12] is row 2:3, col 4.
[axSpan2, optsSpan2] = mu.subplot(fig2, row, col, [8, 12], ...
    "margins", margins2, ...
    "paddings", paddings2, ...
    "indexMode", "linear", ...
    "divBox", "show");
imagesc(axSpan2, rand(20));
axis(axSpan2, "image");
title(axSpan2, "index = [8, 12], indexMode = ""linear""");

% Another normal tile
[axNormal, optsNormal] = mu.subplot(fig2, row, col, 7, ...
    "margins", margins2, ...
    "paddings", paddings2);
plot(axNormal, sin(linspace(0, 2*pi, 100)), "LineWidth", 1.4);
title(axNormal, "index = 7");

sgtitle(fig2, "mu.subplot spanning index in manual-position mode");

local_annotateSpanning(fig2, optsSpan1, optsSpan2, optsSingle, optsNormal, C);

%% Demo 3: Parent as tiledlayout

fig3 = figure( ...
    "Name", "mu.subplot demo 3: tiledlayout parent", ...
    "WindowState", "maximized");

t = tiledlayout(fig3, 3, 4, ...
    "TileSpacing", "compact", ...
    "Padding", "compact");

title(t, "mu.subplot with tiledlayout parent");

drawnow;

% In tiledlayout mode, mu.subplot delegates layout to nexttile.
% margins/paddings/nSize/shape/alignment are parsed but not applied.

[tx1, topts1] = mu.subplot(t, 3, 4, [1, 1, 2, 2], ...
    "indexMode", "span");
plot(tx1, cumsum(randn(100, 3)), "LineWidth", 1.2);
title(tx1, "tiledlayout: [1, 1, 2, 2]");

[tx2, topts2] = mu.subplot(t, 3, 4, [1, 4]);
bar(tx2, rand(1, 6));
title(tx2, "tiledlayout: [1, 4]");

[tx3, topts3] = mu.subplot(t, 3, 4, [8, 12], ...
    "indexMode", "linear");
imagesc(tx3, peaks(30));
axis(tx3, "image");
title(tx3, "tiledlayout: [8, 12], linear");

[tx4, topts4] = mu.subplot(t, 3, 4, 10);
plot(tx4, rand(10, 1), "-o", "LineWidth", 1.2);
title(tx4, "tiledlayout: index = 10");

local_annotateTiledLayout(fig3, t, ...
    {tx1, tx2, tx3, tx4}, ...
    {topts1, topts2, topts3, topts4}, ...
    C);


%% Demo 4: PositionType in manual-position mode

fig4 = figure( ...
    "Name", "mu.subplot demo 4: PositionType", ...
    "WindowState", "maximized");

margins4  = [0.07, 0.05, 0.14, 0.08];
paddings4 = [0.10, 0.10, 0.16, 0.14];

x = linspace(0, 2*pi, 200);

% Old behavior:
%   Computed target box -> ax.Position.
%   xlabel/ylabel/title/tick labels may extend outside the target box.
[axP, optsP] = mu.subplot(fig4, 1, 2, 1, ...
    "margins", margins4, ...
    "paddings", paddings4, ...
    "PositionType", "position");
plot(axP, x, sin(x), "LineWidth", 1.3);
title(axP, "PositionType = ""position""");
xlabel(axP, "Long xlabel: decorations can grow outside the computed target box");
ylabel(axP, "Long ylabel");
grid(axP, "on");

% New behavior:
%   Computed target box -> ax.OuterPosition.
%   MATLAB shrinks ax.Position so decorations stay inside the target box.
[axO, optsO] = mu.subplot(fig4, 1, 2, 2, ...
    "margins", margins4, ...
    "paddings", paddings4, ...
    "PositionType", "outerposition");
plot(axO, x, cos(x), "LineWidth", 1.3);
title(axO, "PositionType = ""outerposition""");
xlabel(axO, "Long xlabel: decorations are constrained by ax.OuterPosition");
ylabel(axO, "Long ylabel");
grid(axO, "on");

drawnow;
pause(0.05);
drawnow;

local_annotatePositionType(fig4, axP, optsP, axO, optsO, C);

annotation(fig4, "textbox", [0.10, 0.015, 0.80, 0.030], ...
    "String", "PositionType controls which axes box receives the computed target rectangle: target -> ax.Position (left) or target -> ax.OuterPosition (right).", ...
    "Color", C.grid, ...
    "EdgeColor", C.grid, ...
    "BackgroundColor", "w", ...
    "FontWeight", "bold", ...
    "HorizontalAlignment", "center");

%% Local helper functions
function local_annotatePositionType(fig, axP, optsP, axO, optsO, C)
%LOCAL_ANNOTATEPOSITIONTYPE Annotate PositionType behavior.
%
% Green dashed box  : computed target box from mu.subplot
% Blue solid box    : live ax.Position
% Orange dotted box : live ax.OuterPosition

drawnow;
