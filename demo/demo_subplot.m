    "EdgeColor", C.grid, ...
    "BackgroundColor", "w", ...
    "HorizontalAlignment", "center", ...
    "FontWeight", "bold");
end

function local_annotatePositionTypeOne(fig, ax, opts, titleText, C, anchor)
%LOCAL_ANNOTATEPOSITIONTYPEONE Annotate one axes for PositionType demo.

targetPos = local_getOptPosition(opts, "axesTargetPosition", "axesPosition");
[pos, outerPos] = local_getLiveAxesPositions(ax);

local_rectWithLabel(fig, targetPos, ...
    "computed target box", C.span, anchor, "--", 1.8);

local_rectWithLabel(fig, pos, ...
    "live ax.Position", C.padding, "southeast", "-", 1.4);

local_rectWithLabel(fig, outerPos, ...
    "live ax.OuterPosition", C.outer, "southwest", ":", 1.8);

% Panel title note, placed above target box.
targetPos = local_clipNormPos(targetPos);
annotation(fig, "textbox", ...
    [targetPos(1), min(targetPos(2) + targetPos(4) + 0.050, 0.94), targetPos(3), 0.04], ...
    "String", titleText, ...
    "Color", C.grid, ...
    "EdgeColor", "none", ...
    "BackgroundColor", "w", ...
    "HorizontalAlignment", "center", ...
    "FontWeight", "bold");
end

function pos = local_getOptPosition(opts, primaryName, fallbackName)
%LOCAL_GETOPTPOSITION Get a position field from opts with fallback.

if isfield(opts, primaryName) && ~isempty(opts.(primaryName))
    pos = opts.(primaryName);
elseif isfield(opts, fallbackName) && ~isempty(opts.(fallbackName))
    pos = opts.(fallbackName);
else
    error("Cannot find position field '%s' or '%s' in opts.", primaryName, fallbackName);
end
end

function [pos, outerPos] = local_getLiveAxesPositions(ax)
%LOCAL_GETLIVEAXESPOSITIONS Get live axes Position and OuterPosition.

oldUnits = ax.Units;
ax.Units = "normalized";
pos = ax.Position;
outerPos = ax.OuterPosition;
ax.Units = oldUnits;

pos = local_clipNormPos(pos);
outerPos = local_clipNormPos(outerPos);
end

function local_rectWithLabel(fig, pos, label, color, anchor, lineStyle, lineWidth)
%LOCAL_RECTWITHLABEL Draw a rectangle with a nearby label.

pos = local_clipNormPos(pos);

annotation(fig, "rectangle", pos, ...
    "Color", color, ...
    "LineStyle", lineStyle, ...
    "LineWidth", lineWidth);

local_labelNearBox(fig, pos, label, color, anchor);
end

function local_labelNearBox(fig, pos, label, color, anchor)
%LOCAL_LABELNEARBOX Add a label near a rectangle.

pos = local_clipNormPos(pos);

switch lower(string(anchor))
    case "northwest"
        textPos = [pos(1), min(pos(2) + pos(4) + 0.006, 0.95), 0.28, 0.04];
        hAlign = "left";

    case "northeast"
        textPos = [max(pos(1) + pos(3) - 0.28, 0.01), min(pos(2) + pos(4) + 0.006, 0.95), 0.28, 0.04];
        hAlign = "right";

    case "southwest"
        textPos = [pos(1), max(pos(2) - 0.046, 0.01), 0.28, 0.04];
        hAlign = "left";

    case "southeast"
        textPos = [max(pos(1) + pos(3) - 0.28, 0.01), max(pos(2) - 0.046, 0.01), 0.28, 0.04];
        hAlign = "right";

    otherwise
        textPos = [pos(1), min(pos(2) + pos(4) + 0.006, 0.95), 0.28, 0.04];
        hAlign = "left";
end

annotation(fig, "textbox", textPos, ...
    "String", label, ...
    "Color", color, ...
    "EdgeColor", "none", ...
    "BackgroundColor", "w", ...
    "HorizontalAlignment", hAlign, ...
    "FontWeight", "bold");
end


