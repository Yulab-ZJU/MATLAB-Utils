function local_annotateTiledLayout(fig, t, axList, optsList, C)
%LOCAL_ANNOTATETILEDLAYOUT Add annotations for tiledlayout mode.
%
% In tiledlayout mode, axes positions are controlled by nexttile. Therefore
% annotation rectangles are computed from the actual axes pixel positions.

drawnow;

try
    tPos = local_normPosInFigure(t, fig);
    annotation(fig, "rectangle", tPos, ...
        "Color", C.grid, ...
        "LineStyle", "--", ...
        "LineWidth", 1.4);
catch
    % Some MATLAB versions do not expose a reliable pixel position for
    % tiledlayout. Axes-level annotations below are still useful.
end

for k = 1:numel(axList)
    ax = axList{k};
    opts = optsList{k};

    pos = local_normPosInFigure(ax, fig);

    label = sprintf( ...
        "tileIndex=%d, span=[%d,%d]", ...
        opts.tileIndex, opts.rowSpan, opts.colSpan);

    local_boxWithLabel(fig, pos, label, C.tile, "northeast");
end

annotation(fig, "textbox", [0.08, 0.01, 0.84, 0.03], ...
    "String", "In tiledlayout mode, opts.axesPosition reports MATLAB-managed axes position; opts.divPosition/drawablePosition are empty.", ...
    "Color", C.tile, ...
    "EdgeColor", C.tile, ...
    "BackgroundColor", "w", ...
    "HorizontalAlignment", "center");
end

